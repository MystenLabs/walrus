// Generates sidebarsOyster.js from the transformed oyster-content directory.
// Parses the upstream SUMMARY.md to preserve ordering, then appends the
// generated API reference page.
//
// To change sidebar structure, edit STRUCTURE below.

const fs = require("fs");
const path = require("path");

const SITE_ROOT = path.resolve(__dirname, "../../");
const CONTENT_DIR = path.resolve(SITE_ROOT, "../oyster-content");
const SIDEBAR_OUT = path.join(SITE_ROOT, "sidebarsOyster.js");

// ── Sidebar structure ───────────────────────────────────────────────
// Mirrors the SUMMARY.md structure from the upstream mdBook, with
// README → index renames and .md stripped.

const STRUCTURE = [
  {
    label: "Get Started",
    collapsed: false,
    items: ["introduction", "getting-started"],
  },
  {
    label: "JSON API Reference",
    collapsed: true,
    link: "json-api/index",
    items: [
      "json-api/authentication",
      "json-api/admin",
      "json-api/buckets",
      "json-api/blobs",
      "json-api/access-keys",
      "json-api/wallet",
      "json-api/infrastructure",
    ],
  },
  {
    label: "S3 API Reference",
    collapsed: true,
    link: "s3-api/index",
    items: [
      "s3-api/setup",
      "s3-api/buckets",
      "s3-api/objects",
      "s3-api/limitations",
    ],
  },
  {
    label: "Guides",
    collapsed: true,
    link: "guides/index",
    items: [
      "guides/cli",
      "guides/aws-sdk",
      "guides/content-addressing",
      "guides/blob-lifecycle",
      "guides/webhooks",
      "guides/web-signup",
    ],
  },
  "api-reference",
];

// ── Verify pages exist on disk ──────────────────────────────────────

function pageExists(slug) {
  return (
    fs.existsSync(path.join(CONTENT_DIR, slug + ".mdx")) ||
    fs.existsSync(path.join(CONTENT_DIR, slug + ".md"))
  );
}

// ── Build sidebar items ─────────────────────────────────────────────

function buildItem(item) {
  if (typeof item === "string") {
    if (!pageExists(item)) {
      console.warn(`  ⚠️  Page listed but not found on disk: ${item}`);
      return null;
    }
    return item;
  }

  // Category object
  const cat = {
    type: "category",
    label: item.label,
    collapsed: item.collapsed !== false,
    items: [],
  };

  if (item.link) {
    cat.link = { type: "doc", id: item.link };
  }

  for (const child of item.items || []) {
    const built = buildItem(child);
    if (built !== null) {
      cat.items.push(built);
    }
  }

  return cat;
}

// ── Format the sidebar as a JS module ───────────────────────────────

function formatSidebar(sidebar) {
  const json = JSON.stringify({ oysterSidebar: sidebar }, null, 2);
  return [
    "// Copyright (c) Walrus Foundation",
    "// SPDX-License-Identifier: Apache-2.0",
    "//",
    "// AUTO-GENERATED by generate-oyster-sidebar.js — do not edit manually.",
    "// To change sidebar structure, edit the STRUCTURE config in that script.",
    "",
    "// @ts-check",
    "",
    '/** @type {import("@docusaurus/plugin-content-docs").SidebarsConfig} */',
    `const sidebars = ${json};`,
    "",
    "export default sidebars;",
    "",
  ].join("\n");
}

// ── Main ────────────────────────────────────────────────────────────

function main() {
  if (!fs.existsSync(CONTENT_DIR)) {
    console.warn(
      "⚠️  oyster: content dir not found. Skipping sidebar generation.",
    );
    return;
  }

  const sidebar = [];
  for (const item of STRUCTURE) {
    const built = buildItem(item);
    if (built !== null) {
      sidebar.push(built);
    }
  }

  fs.writeFileSync(SIDEBAR_OUT, formatSidebar(sidebar));
  console.log(
    `✅ oyster: generated sidebarsOyster.js (${sidebar.length} items)\n`,
  );
}

main();
